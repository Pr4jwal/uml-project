const access = { "+": "public", "-": "private", "#": "protected" },
  cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : "");
function java(cs) {
  let im = new Set();
  let scan = (t) => {
    if (/List\s*</.test(t)) im.add("java.util.List");
    if (/LocalDate/.test(t)) im.add("java.time.LocalDate");
    if (/BigDecimal/.test(t)) im.add("java.math.BigDecimal");
  };
  cs.flatMap((c) => [...c.fields, ...c.methods]).forEach((x) => scan(x.type));
  let body = cs
    .map((c) => {
      let fs = c.fields
          .filter((f) => f.name && f.type)
          .map((f) => `  ${access[f.v] || "private"} ${f.type} ${f.name};`)
          .join("\n"),
        gs = c.fields
          .filter((f) => f.name && f.type)
          .map(
            (f) =>
              `  public ${f.type} get${cap(f.name)}() {\n    return ${f.name};\n  }\n\n  public void set${cap(f.name)}(${f.type} ${f.name}) {\n    this.${f.name} = ${f.name};\n  }`,
          )
          .join("\n\n"),
        ms = c.methods
          .filter((m) => m.name && m.type)
          .map(
            (m) =>
              `  ${access[m.v] || "public"} ${m.type} ${m.name.includes("(") ? m.name : m.name + "()"} {\n    ${m.type === "void" ? "// TODO: implement" : "return null;"}\n  }`,
          )
          .join("\n\n");
      return `${c.visibility === "package-private" ? "" : c.visibility + " "}class ${c.name || "UnnamedClass"} {\n${[fs, gs, ms].filter(Boolean).join("\n\n")}\n}`;
    })
    .join("\n\n");
  return `${
    im.size
      ? [...im]
          .sort()
          .map((i) => "import " + i + ";")
          .join("\n") + "\n\n"
      : ""
  }// Generated by UML Studio\n\n${body}`;
}
function App() {
  const [cs, setCs] = useState(seed),
    [rs, setRs] = useState(seedR),
    [sel, setSel] = useState("customer"),
    [view, setView] = useState("diagram"),
    [drag, setDrag] = useState(null),
    [query, setQuery] = useState("");
  const can = useRef();
  let ac = cs.find((c) => c.id === sel),
    code = useMemo(() => java(cs), [cs]);
  let uc = (p) =>
      setCs((a) => a.map((c) => (c.id === sel ? { ...c, ...p } : c))),
    um = (k, i, n, v) =>
      uc({ [k]: ac[k].map((x, j) => (j === i ? { ...x, [n]: v } : x)) }),
    add = (k) =>
      uc({
        [k]: [
          ...ac[k],
          {
            v: k === "fields" ? "-" : "+",
            name: k === "fields" ? "newField" : "newMethod()",
            type: k === "fields" ? "String" : "void",
          },
        ],
      }),
    del = (k, i) => uc({ [k]: ac[k].filter((_, j) => j !== i) });
  let save = () => {
    let u = URL.createObjectURL(new Blob([code], { type: "text/x-java" })),
      a = document.createElement("a");
    a.href = u;
    a.download = "UmlClasses.java";
    a.click();
    setTimeout(() => URL.revokeObjectURL(u), 0);
  };
  let addC = () => {
    let id = "class" + Date.now();
    setCs((a) => [
      ...a,
      {
        id,
        name: "NewClass" + (a.length + 1),
        visibility: "public",
        x: 250,
        y: 120,
        color: "#4f86e8",
        fields: [{ v: "-", name: "id", type: "Long" }],
        methods: [],
      },
    ]);
    setSel(id);
    setView("diagram");
  };
  let move = (e) => {
    if (!drag) return;
    let r = can.current.getBoundingClientRect();
    setCs((a) =>
      a.map((c) =>
        c.id === drag.id
          ? {
              ...c,
              x: Math.max(
                0,
                Math.min(r.width - 240, e.clientX - r.left - drag.dx),
              ),
              y: Math.max(0, e.clientY - r.top - drag.dy),
            }
          : c,
      ),
    );
  };
  let remC = () => {
    if (cs.length < 2) return;
    let n = cs.filter((c) => c.id !== sel);
    setCs(n);
    setRs((a) => a.filter((r) => r.from !== sel && r.to !== sel));
    setSel(n[0].id);
  };
  return (
    <main onPointerMove={move} onPointerUp={() => setDrag(null)}>
      <aside className="sidebar">
        <div className="brand">
          <span className="brand-mark">
            <Layers3 size={19} />
          </span>
          <span>
            uml<span>studio</span>
          </span>
        </div>
        <div className="project">
          <small>PROJECT</small>
          <strong>Shop System</strong>
          <span>
            {cs.length} classes · {rs.length} relations
          </span>
        </div>
        <nav>
          <button
            className={view === "diagram" ? "nav-active" : ""}
            onClick={() => setView("diagram")}
          >
            <Box />
            Diagram
          </button>
          <button
            className={view === "code" ? "nav-active" : ""}
            onClick={() => setView("code")}
          >
            <Code2 />
            Generated code
          </button>
        </nav>
        <div className="side-bottom">
          <button>
            <Settings2 />
            Settings
          </button>
        </div>
      </aside>
      <section className="workspace">
        <header>
          <div className="crumb">
            Projects <span>/</span> Shop System <span>/</span>{" "}
            <b>Class Diagram</b>
          </div>
          <div className="head-actions">
            <div className="search-wrap">
              <Search size={16} />
              <input
                placeholder="Search"
                value={query}
                onChange={(e) => setQuery(e.target.value)}
              />
            </div>
            <button className="save">
              <Save size={15} /> Saved
            </button>
            <button className="primary" onClick={save}>
              <Download size={16} /> Export Java
            </button>
          </div>
        </header>
        <div className="toolbar">
          <button className="tool active">
            <MousePointer2 />
            Select
          </button>
          <button
            className="tool"
            onClick={() => {
              let t = cs.find((c) => c.id !== sel);
              if (t)
                setRs((a) => [
                  ...a,
                  {
                    id: Date.now(),
                    from: sel,
                    to: t.id,
                    label: "uses",
                    kind: "association",
                  },
                ]);
            }}
          >
            <Link2 />
            Relationship
          </button>
          <i />
          <button className="tool" onClick={addC}>
            <Plus />
            Add class
          </button>
          <button
            className="tool"
            onClick={() =>
              setCs((a) =>
                a.map((c, i) => ({
                  ...c,
                  x: 70 + (i % 3) * 300,
                  y: 90 + Math.floor(i / 3) * 250,
                })),
              )
            }
          >
            <Sparkles />
            Auto layout
          </button>
        </div>
        <div className="canvas" ref={can}>
          {view === "code" ? (
            <div className="code-view">
              <div className="code-heading">
                <div>
                  <FileCode2 />
                  <span>
                    <b>Java source preview</b>
                    <small>Generated from your diagram</small>
                  </span>
                </div>
                <button className="primary" onClick={save}>
                  <Download size={16} />
                  Download .java
                </button>
              </div>
              <pre>{code}</pre>
            </div>
          ) : (
            <>
              <svg className="relations">
                {rs.map((r) => {
                  let a = cs.find((c) => c.id === r.from),
                    b = cs.find((c) => c.id === r.to);
                  if (!a || !b) return null;
                  return (
                    <g key={r.id}>
                      <line
                        x1={a.x + 120}
                        y1={a.y + 75}
                        x2={b.x + 120}
                        y2={b.y + 75}
                        className={r.kind}
                      />
                      <text
                        x={(a.x + b.x + 240) / 2}
                        y={(a.y + b.y + 150) / 2 - 10}
                      >
                        {r.label}
                      </text>
                    </g>
                  );
                })}
              </svg>
              {cs
                .filter((c) =>
                  c.name.toLowerCase().includes(query.toLowerCase()),
                )
                .map((c) => (
                  <div
                    key={c.id}
                    className={"uml-card " + (sel === c.id ? "selected" : "")}
                    style={{ left: c.x, top: c.y }}
                    onPointerDown={(e) => {
                      let r = e.currentTarget.getBoundingClientRect();
                      setSel(c.id);
                      setDrag({
                        id: c.id,
                        dx: e.clientX - r.left,
                        dy: e.clientY - r.top,
                      });
                    }}
                  >
                    <div
                      className="card-title"
                      style={{ borderTopColor: c.color }}
                    >
                      <GripVertical size={15} />
                      <b>{c.name || "UnnamedClass"}</b>
                      <button
                        onPointerDown={(e) => e.stopPropagation()}
                        onClick={remC}
                      >
                        <Trash2 size={14} />
                      </button>
                    </div>
                    <div className="members">
                      {c.fields.map((f, i) => (
                        <p key={i}>
                          <em>{f.v}</em>
                          {f.name}
                          <span>: {f.type}</span>
                        </p>
                      ))}
                    </div>
                    {c.methods.length > 0 && (
                      <div className="members methods">
                        {c.methods.map((m, i) => (
                          <p key={i}>
                            <em>{m.v}</em>
                            {m.name}
                            <span>: {m.type}</span>
                          </p>
                        ))}
                      </div>
                    )}
                  </div>
                ))}
            </>
          )}
        </div>
      </section>
      <aside className="inspector">
        <div className="inspector-title">
          <b>{view === "code" ? "Code preview" : "Properties"}</b>
          {view === "diagram" && (
            <button onClick={() => setView("code")}>
              <X size={17} />
            </button>
          )}
        </div>
        {view === "diagram" && ac && (
          <div className="property-content">
            <label>
              CLASS NAME
              <input
                value={ac.name}
                onChange={(e) =>
                  uc({
                    name: e.target.value
                      .replace(/[^A-Za-z\d_$]/g, "")
                      .replace(/^\d/, ""),
                  })
                }
              />
            </label>
            <label>
              VISIBILITY
              <select
                value={ac.visibility}
                onChange={(e) => uc({ visibility: e.target.value })}
              >
                <option>public</option>
                <option>protected</option>
                <option>private</option>
                <option>package-private</option>
              </select>
            </label>
            <hr />
            <Editor
              title="ATTRIBUTES"
              kind="fields"
              items={ac.fields}
              add={add}
              edit={um}
              remove={del}
            />
            <hr />
            <Editor
              title="METHODS"
              kind="methods"
              items={ac.methods}
              add={add}
              edit={um}
              remove={del}
            />
            <hr />
            <div className="group-heading">
              <span>RELATIONSHIPS</span>
            </div>
            {rs
              .filter((r) => r.from === sel || r.to === sel)
              .map((r) => (
                <div className="relation-editor" key={r.id}>
                  <input
                    value={r.label}
                    onChange={(e) =>
                      setRs((a) =>
                        a.map((x) =>
                          x.id === r.id ? { ...x, label: e.target.value } : x,
                        ),
                      )
                    }
                  />
                  <select
                    value={r.kind}
                    onChange={(e) =>
                      setRs((a) =>
                        a.map((x) =>
                          x.id === r.id ? { ...x, kind: e.target.value } : x,
                        ),
                      )
                    }
                  >
                    <option value="association">association</option>
                    <option value="composition">composition</option>
                  </select>
                  <button
                    onClick={() => setRs((a) => a.filter((x) => x.id !== r.id))}
                  >
                    <Trash2 size={14} />
                  </button>
                </div>
              ))}
          </div>
        )}
      </aside>
    </main>
  );
}
function Editor({ title, kind, items, add, edit, remove }) {
  return (
    <>
      <div className="group-heading">
        <span>
          {title} <small>{items.length}</small>
        </span>
        <button onClick={() => add(kind)}>
          <Plus size={15} /> Add
        </button>
      </div>
      {items.map((m, i) => (
        <div className="member-editor" key={i}>
          <select
            value={m.v}
            onChange={(e) => edit(kind, i, "v", e.target.value)}
          >
            <option>+</option>
            <option>-</option>
            <option>#</option>
          </select>
          <input
            value={m.name}
            onChange={(e) => edit(kind, i, "name", e.target.value)}
          />
          <input
            value={m.type}
            onChange={(e) => edit(kind, i, "type", e.target.value)}
          />
          <button onClick={() => remove(kind, i)}>
            <Trash2 size={14} />
          </button>
        </div>
      ))}
    </>
  );
}
createRoot(document.getElementById("root")).render(<App />);
